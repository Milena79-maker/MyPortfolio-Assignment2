import express from "express";
import userCtrl from "../controllers/user.controller.js";
import requireAuth, { requireOwner } from "../helpers/auth.middleware.js";
const router = express.Router();
router.route("/api/users").post(userCtrl.create);
router.route("/api/users").get(userCtrl.list);
router.param("userId", userCtrl.userByID);
router.route("/api/users/:userId").get(requireAuth, requireOwner, userCtrl.read);
router.route("/api/users/:userId").put(requireAuth, requireOwner, userCtrl.update);
router.route("/api/users/:userId").delete(requireAuth, requireOwner, userCtrl.remove);
router.post("/api/users/signin", userCtrl.signin);
export default router;
